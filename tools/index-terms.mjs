// Gathers candidate index terms from each chapter, for the book's index.
//
// usage: node tools/index-terms.mjs > notes/index-terms.md
//
// The book has two indexes:
//   general  concepts (terms in **bold**, which by the book's convention mark
//            the place a term is defined) and OpenType table and feature tags
//   code     HarfBuzz's own names: API and macros, types and structs, and
//            source files
// For each page in book/toc.txt that has been written, it lists both, then
// gives each index as one alphabetical list, with the chapters each term is in.
// Terms in fenced blocks (code, shape, trace...) are left out. Where a term
// should be found, and its synonyms and "see also"s, are decided by hand in
// notes/index-notes.md; this only gathers.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { boldTerm, canon, identifier, readNotes } from "./index-lib.mjs";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const BOOK = path.join(ROOT, "book");

// Chapters are numbered through the [part] sections, planned ones included,
// as the book numbers them.
const pages = [];
{
  let inPart = false, n = 0;
  for (const raw of fs.readFileSync(path.join(BOOK, "toc.txt"), "utf8").split("\n")) {
    const l = raw.trim();
    if (l.startsWith("[")) { inPart = l.startsWith("[part]"); continue; }
    if (!inPart || !l || l.startsWith("#")) continue;
    n++;
    if (!l.startsWith("?")) pages.push({ page: l, n });
  }
}

const { notTerms: NOT_TERMS } = readNotes(ROOT);

// Prose only: drop fenced blocks.
const prose = (md) => md.replace(/^```[\s\S]*?^```/gm, "");

const sorted = (items) => [...items].sort((a, b) => a.localeCompare(b, "en", { sensitivity: "base" }));

const out = ["# Index terms, by chapter", "",
  "Generated by `tools/index-terms.mjs` from the chapters as they stand: regenerate it rather than editing it. " +
  "Decisions about entries (synonyms, “see also”, main entries) are in `index-notes.md`.", "",
  "The book has two indexes. The **general index** holds concepts, and OpenType table and feature tags. " +
  "The **code index** holds HarfBuzz’s own names: API and macros, types and structs, and source files.", ""];
const general = new Map(), code = new Map();          // term -> set of chapter numbers
const note = (index, term, n) => { if (!index.has(term)) index.set(term, new Set()); index.get(term).add(n); };


for (const { page, n } of pages) {
  const file = path.join(BOOK, page);
  if (!fs.existsSync(file)) continue;
  const md = fs.readFileSync(file, "utf8");
  const title = (md.match(/^# (.+)$/m) || [, page])[1];
  const text = prose(md);
  const concepts = new Map();
  for (const m of text.matchAll(/\*\*([^*\n]+?)\*\*/g)) {
    const t = boldTerm(m[1]);
    if (!t) continue;
    const key = t.toLowerCase();
    if (NOT_TERMS.has(canon(t))) continue;
    if (!concepts.has(key)) concepts.set(key, t);
  }
  const ids = { api: new Set(), type: new Set(), tag: new Set(), file: new Set() };
  for (const m of text.matchAll(/`([^`\n]+)`/g)) {
    const r = identifier(m[1]);
    if (r) ids[r[0]].add(r[1]);
  }
  if (!concepts.size && !Object.values(ids).some((s) => s.size)) continue;   // a placeholder
  out.push(`## ${n}. ${title}`, "", `\`${page}\``, "");
  const line = (label, items, fmt = (x) => x) =>
    items.length && out.push(`* ${label} (${items.length}): ${sorted(items).map(fmt).join(", ")}`);
  const tick = (x) => "`" + x + "`";
  out.push("General index:", "");
  line("Concepts", [...concepts.values()]);
  line("Tables and tags", [...ids.tag], tick);
  out.push("", "Code index:", "");
  line("API and macros", [...ids.api], tick);
  line("Types and structs", [...ids.type], tick);
  line("Source files", [...ids.file], tick);
  out.push("");
  for (const t of concepts.values()) note(general, t, n);
  for (const t of ids.tag) note(general, tick(t), n);
  for (const k of ["api", "type", "file"]) for (const t of ids[k]) note(code, tick(t), n);
}

const bare = (t) => t.replace(/`/g, "").replace(/^_+/, "");
const all = (index) => [...index].sort((a, b) => bare(a[0]).localeCompare(bare(b[0]), "en", { sensitivity: "base" }))
  .map(([t, ns]) => `* ${t}: ${[...ns].join(", ")}`);
out.push("## The general index so far", "", "Each term, with the chapters it is in.", "", ...all(general), "",
         "## The code index so far", "", ...all(code), "");

process.stdout.write(out.join("\n"));
